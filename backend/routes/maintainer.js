// Create pull request
const createPullRequest = async (owner, repo, title, body, files) => {
  try {
    // Get default branch
    const { data: repoData } = await octokit.repos.get({ owner, repo });
    const defaultBranch = repoData.default_branch;
    
    // Create new branch
    const branchName = `nogaslabs-maintainer-${Date.now()}`;
    await octokit.git.createRef({
      owner,
      repo,
      ref: `refs/heads/${branchName}`,
      sha: repoData.default_branch === 'main' || repoData.default_branch === 'master' 
        ? (await octokit.repos.getBranch({ owner, repo, branch: defaultBranch })).data.commit.sha
        : repoData.default_branch
    });
    
    // Create/ update files
    for (const [filePath, content] of Object.entries(files)) {
      try {
        await octokit.repos.createOrUpdateFileContents({
          owner,
          repo,
          path: filePath,
          message: `Add ${filePath}`,
          content: Buffer.from(content).toString('base64'),
          branch: branchName
        });
      } catch (error) {
        // File might already exist, try to update
        if (error.status === 409) {
          const { data: existingFile } = await octokit.repos.getContent({
            owner,
            repo,
            path: filePath,
            ref: defaultBranch
          });
          
          await octokit.repos.createOrUpdateFileContents({
            owner,
            repo,
            path: filePath,
            message: `Update ${filePath}`,
            content: Buffer.from(content).toString('base64'),
            sha: existingFile.sha,
            branch: branchName
          });
        }
      }
    }
    
    // Create pull request
    const pr = await octokit.pulls.create({
      owner,
      repo,
      title,
      body,
      head: branchName,
      base: defaultBranch
    });
    
    return pr;
  } catch (error) {
    console.error('Create PR error:', error);
    throw error;
  }
};

