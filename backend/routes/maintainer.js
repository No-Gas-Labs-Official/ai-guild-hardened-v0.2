// Trigger auto-maintenance
router.post('/:repoId/maintain', authenticateToken, async (req, res) => {
  try {
    const { repoId } = req.params;
    
    // Get repository info
    const repoResult = await pool.query('SELECT * FROM repositories WHERE id = $1', [repoId]);
    if (repoResult.rows.length === 0) {
      return res.status(404).json({ error: 'Repository not found' });
    }
    
    const repo = repoResult.rows[0];
    
    // Start maintenance in background
    autoMaintainRepository(repo.id, repo.owner, repo.name).catch(console.error);
    
    res.json({ message: 'Repository maintenance started' });
  } catch (error) {
    console.error('Maintenance trigger error:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

